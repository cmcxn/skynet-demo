local passed, failed = 0, 0
local function test(name, fn)
    local ok, err = pcall(fn)
    if ok then passed = passed + 1; print("PASS " .. name)
    else failed = failed + 1; print("FAIL " .. name .. ": " .. tostring(err)) end
end
local function mod(name)
    local ok, value = pcall(require, "skynet_llm." .. name)
    assert(ok, "missing implementation: skynet_llm." .. name)
    return value
end
local function rejects(fn, ...)
    local value, err = fn(...)
    assert(value == nil and type(err) == "table" and type(err.code) == "string")
    return err
end
local function throws(fn, ...) assert(not pcall(fn, ...), "expected strict rejection") end
local function parse(s) return mod("json").decode(s) end

test("JSON preserves null and empty container identity", function()
    local j = mod("json")
    assert(j.encode(j.decode('{"a":[],"b":{},"c":null}')) == '{"a":[],"b":{},"c":null}')
    assert(j.encode(j.array{}) == "[]" and j.encode(j.object{}) == "{}")
    assert(j.decode("null") == j.null and j.encode({1,2}) == "[1,2]")
end)
test("JSON decodes UTF-8 and surrogate pairs", function()
    local j = mod("json")
    assert(j.decode('"\\u4f60\\u597d \\ud83d\\ude00"') == "你好 😀")
    assert(j.decode(j.encode("\0\1\n你好")) == "\0\1\n你好")
end)
test("JSON rejects malformed syntax, unicode and duplicate keys", function()
    local j = mod("json")
    for _, s in ipairs({'', '[1,]', '{"x":1,}', '{"x":1,"x":2}', '01', '+1', '1.', '1e', 'true false', '"\\ud800"', '"\\udc00"', '"\\ud800\\u0041"', '"\\x"', '"\n"', '"' .. string.char(255) .. '"'}) do throws(j.decode, s) end
end)
test("JSON rejects cycles, sparse/mixed arrays and nonfinite values", function()
    local j = mod("json"); local cycle = {}; cycle.self = cycle
    for _, value in ipairs({cycle, {[1]=1,[3]=3}, {[1]=1,x=2}, math.huge, -math.huge, 0/0, function() end}) do throws(j.encode, value) end
    throws(j.decode, "1e999")
    throws(j.encode, j.array{[2]=2})
end)
test("JSON bounds nesting and rejects nonstring object keys", function()
    local j = mod("json"); local deep = {}; local p = deep
    for _ = 1, 140 do p.a = {}; p = p.a end
    throws(j.encode, deep); throws(j.decode, string.rep("[",140) .. "0" .. string.rep("]",140))
    throws(j.encode, j.object{[1]="bad"})
end)
test("JSON round trips finite doubles without losing precision or integer range",function()
    local j=mod("json")
    for _, value in ipairs({1.0000000000000002,1.000000000000001,-1.000000000000001,0.1,1e300,5e-324}) do
        assert(j.decode(j.encode(value))==value,"finite double lost precision")
    end
    assert(j.encode(9223372036854775807)=="9223372036854775807")
    assert(j.encode(-9223372036854775807-1)=="-9223372036854775808")
    assert(1/j.decode(j.encode(-0.0)) == -math.huge,"negative zero lost its sign")
end)
test("JSON encoding enforces an incremental byte budget including escaped strings",function()
    local j=mod("json"); local value={a=j.array{"\n",j.null}}
    local expected='{"a":["\\n",null]}'
    assert(j.encode(value,{max_bytes=#expected})==expected)
    throws(j.encode,value,{max_bytes=#expected-1})
    assert(j.encode("\n",{max_bytes=4})=='"\\n"'); throws(j.encode,"\n",{max_bytes=3})
    local cycle={}; cycle.self=cycle
    local ok,err=pcall(j.encode,{string.rep("x",1000000),cycle},{max_bytes=32})
    assert(not ok and tostring(err):find("JSON byte limit exceeded",1,true),"encoder traversed beyond its byte budget")
    for _, limit in ipairs({0,-1,1.5,math.huge,"8"}) do throws(j.encode,{}, {max_bytes=limit}) end
end)

local function chat_result()
    return parse('{"id":"chat_1","choices":[{"index":0,"finish_reason":"tool_calls","message":{"role":"assistant","content":null,"tool_calls":[{"id":"call_a","type":"function","function":{"name":"a","arguments":"{\\"n\\":1}"}},{"id":"call_b","type":"function","function":{"name":"b","arguments":"{}"}}]}}]}')
end
test("Chat helper appends complete assistant and ordered results without mutation", function()
    local j, tools = mod("json"), mod("tools")
    local body = parse('{"model":"m","messages":[{"role":"user","content":"hi"}],"extension":{"a":[]}}')
    local res = chat_result(); local before = j.encode(body)
    local next_body = assert(tools.continue_chat(body, {data=res}, {{tool_call_id="call_b",output="B"},{tool_call_id="call_a",output="A"}}))
    assert(j.encode(body) == before and #next_body.messages == 4)
    assert(next_body.messages[2].content == j.null and next_body.messages[3].tool_call_id == "call_a" and next_body.messages[4].content == "B")
    next_body.extension.a[1] = "changed"; assert(#body.extension.a == 0)
end)
test("Chat helper rejects incomplete and ambiguous choice continuation", function()
