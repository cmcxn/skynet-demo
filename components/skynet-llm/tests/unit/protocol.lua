    res.choices[1].finish_reason="tool_calls"; res.choices[2]=parse('{"index":1,"finish_reason":"stop","message":{"role":"assistant","content":"ok"}}')
    rejects(t.continue_chat,body,res,results)
    assert(t.continue_chat(body,res,results,{choice_index=0}))
    rejects(t.continue_chat,body,res,results,{choice_index=1})
end)
